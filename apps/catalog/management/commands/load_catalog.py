class Command(BaseCommand):
    help = "Заполняет базу данных каталога (Категории, Атрибуты, Товары)"

    def handle(self, *args, **options):
        self.stdout.write(self.style.WARNING("Начинаем заполнение базы данных каталога..."))

        # Оборачиваем всё в транзакцию (если будет ошибка, база не сломается наполовину)
        with transaction.atomic():

            # ОПЦИОНАЛЬНО: Очистка старых данных перед загрузкой.
            # Расскомментируй, если хочешь, чтобы скрипт каждый раз создавал базу с нуля
            # Category.objects.all().delete()
            # self.stdout.write("Старые данные удалены.")

            for cat_idx, cat_data in enumerate(CATALOG_DATA, start=1):
                # 1. Создаем категорию
                category, cat_created = Category.objects.get_or_create(
                    name=cat_data["category"],
                    defaults={
                        "description": cat_data["description"],
                        "sort_order": cat_idx * 10
                    }
                )

                # 2. Создаем атрибуты для категории
                attr_objects = {}
                for attr_idx, attr_name in enumerate(cat_data["attributes"], start=1):
                    attribute, _ = Attribute.objects.get_or_create(
                        category=category,
                        name=attr_name,
                        defaults={"sort_order": attr_idx * 10}
                    )
                    attr_objects[attr_name] = attribute

                # 3. Создаем товары
                for prod_idx, prod_data in enumerate(cat_data["products"], start=1):
                    product, prod_created = Product.objects.get_or_create(
                        category=category,
                        name=prod_data["name"],
                        defaults={
                            "price": Decimal(prod_data["price"]),
                            "sort_order": prod_idx * 10
                        }
                    )

                    if prod_created:
                        # 4. Привязываем значения атрибутов
                        for attr_name, attr_value in prod_data["attrs"].items():
                            ProductAttributeValue.objects.create(
                                product=product,
                                attribute=attr_objects[attr_name],
                                value=attr_value
                            )

                self.stdout.write(
                    self.style.SUCCESS(f"Загружена категория: {category.name} ({len(cat_data['products'])} товаров)"))

        self.stdout.write(self.style.SUCCESS("\n✅ База данных успешно заполнена!"))
